#!/usr/bin/env bash
# Релиз продакшена одной командой: версия → тег → сборка → выкатка → проверка, что приложение
# отвечает. Всю работу делает werf.sh, здесь только имя команды — чтобы в каждом репозитории не
# заводить своего скрипта релиза и не разъезжаться с остальными.
#
#   release.sh                # patch
#   release.sh minor
#   release.sh --dry-run      # весь план: настройки, версия, каждая команда. Ничего не делает
#   release.sh --deploy-only  # повторить сборку и выкатку последнего тега, нового не выпуская
#   release.sh --ghcr         # образы в ghcr, как делал CI (по умолчанию — локальный реестр)
set -euo pipefail

# readlink: скрипт зовут через симлинк ~/bin/release.sh, а werf.sh лежит рядом с оригиналом.
SCRIPT_DIR=$(cd "$(dirname "$(readlink -f "$0")")" && pwd)
exec "$SCRIPT_DIR/werf.sh" production "$@"
